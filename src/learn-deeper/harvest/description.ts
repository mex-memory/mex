import type { PinnedTree } from "../git.js";
import { contrastive, generalising } from "./evidence.js";

const templatePath = /^(?:\.github\/|docs\/)?pull_request_template(?:\.(?:md|txt|rst)|\/[^/]+)?$/iu;
const checkbox = /^\s*(?:[-*+]|\d{1,3}[.)])\s+\[[ xX]\](?:\s|$)/u;
const decisionsHeading = /^(?:#{1,4}\s*Decisions?\b.*|\*\*Decisions?\*\*:?[ \t]*)$/iu;
const chosen = /\b(?:decided|decisions?|chose|chosen|opted|trade-?offs?|alternatives?|in favou?r of|on purpose|intentional(?:ly)?|deliberate(?:ly)?|by design)\b/iu;
const lineKey = (line: string) => line.trim().replace(/\s+/gu, " ").toLowerCase();
const headingLevel = (line: string) => /^ {0,3}(#{1,6})\s/u.exec(line)?.[1]!.length;
const indent = (line: string) => line.length - line.trimStart().length;

const templates = new WeakMap<PinnedTree, Promise<ReadonlySet<string>>>();

/** The lines of the repository's pull request templates: nobody wrote those about one change. */
export function templateLines(tree: PinnedTree): Promise<ReadonlySet<string>> {
  let lines = templates.get(tree);
  if (!lines) {
    lines = (async () => {
      const found = new Set<string>();
      for (const path of [...tree.paths()].filter(path => templatePath.test(path)).slice(0, 16)) {
        const text = await tree.read(path);
        for (const line of visible(text?.replace(/\r\n?/gu, "\n") ?? "").split("\n")) if (lineKey(line)) found.add(lineKey(line));
      }
      return found;
    })();
    templates.set(tree, lines);
  }
  return lines;
}

/** A marker a program leaves (`review_summary`, `BODY_BEGIN`, "auto-generated …"), unlike a template's sentence. */
const opens = (comment: string) => !/(?:^|[_:-])end$|^end\b|ignore|disable|enable/iu.test(comment)
  && (/^[\w.:-]*[_:-][\w.:-]*$/u.test(comment) || /\bauto(?:matically)?[ -]?generated\b|\bgenerated by\b/iu.test(comment));
const closes = (comment: string, open: string) => comment === `/${open}` || (/\s/u.test(open) ? /^end\b/iu.test(comment)
  : /(?:begin|start)$/iu.test(open) && comment.toLowerCase() === open.toLowerCase().replace(/(?:begin|start)$/u, "end"));

/** The body without its HTML comments, which the page never shows, and without the text a program put between them. */
function visible(body: string): string {
  const comments: Array<{ start: number; end: number; text: string }> = [];
  for (let start = body.indexOf("<!--"), close; start >= 0; start = body.indexOf("<!--", close + 3)) {
    close = body.indexOf("-->", start + 2);
    if (close < 0) {
      // One left open hides the rest only when it starts its line.
      if (!body.slice(body.lastIndexOf("\n", start) + 1, start).trim()) comments.push({ start, end: body.length, text: "" });
      break;
    }
    comments.push({ start, end: close + 3, text: body.slice(start + 4, close).trim() });
  }
  let shown = "", at = 0;
  for (let i = 0; i < comments.length; i++) {
    const { start, end, text } = comments[i]!;
    shown += body.slice(at, start);
    at = end;
    if (!opens(text)) continue;
    const last = comments.findIndex((comment, j) => j > i && closes(comment.text, text));
    if (last < 0) return shown;
    at = comments[i = last]!.end;
  }
  return shown + body.slice(at);
}

/**
 * What the author wrote in a pull request description: without hidden comments, ticked boxes, the repository's own
 * template lines and the headings left with nothing under them. A template repeated in a hundred descriptions is one
 * statement, and a link in its checklist isn't the author's.
 */
export function authored(body: string, template: ReadonlySet<string> = new Set()): string {
  const kept: Array<{ line: string; level?: number }> = [];
  let box: number | undefined, fence: string | undefined;
  for (const line of visible(body.replace(/\r\n?/gu, "\n")).split("\n")) {
    const mark = /^\s*(`{3}|~{3})/u.exec(line)?.[1];
    if (fence || mark) {
      kept.push({ line });
      fence = fence ? (mark === fence ? undefined : fence) : mark;
      continue;
    }
    if (checkbox.test(line)) { box = indent(line); continue; }
    if (box !== undefined && line.trim()) {
      if (indent(line) > box) continue;
      box = undefined;
    }
    const level = headingLevel(line);
    if (level === undefined && template.has(lineKey(line))) continue;
    kept.push({ line, level });
  }
  // Text is deeper than any heading, the end shallower. A heading with neither text nor a deeper heading under it goes.
  const text: string[] = [];
  let below = 0;
  for (const { line, level } of kept.reverse()) {
    if (level !== undefined && below <= level) continue;
    if (line.trim()) below = level ?? 7;
    text.push(line);
  }
  return text.reverse().join("\n").replace(/\n{3,}/gu, "\n\n").trim();
}

/** Whether a description says what was chosen or ruled out. One that only lists what changed teaches nothing alone. */
export function decides(text: string): boolean {
  return hasDecisionsSection(text) || generalising.test(text) || contrastive(text) || chosen.test(text);
}

export function hasDecisionsSection(body: string): boolean {
  const lines = body.split(/\r?\n/u);
  const start = lines.findIndex(line => decisionsHeading.test(line.trim()));
  const content = lines.slice(start + 1).find(line => line.trim());
  return start >= 0 && content !== undefined && !/^(?:#{1,6}\s|\*\*[^*]+\*\*:?\s*$)/u.test(content.trim());
}

/** The description with its Decisions section first, when it has one. */
export function decisionsFirst(body: string): string {
  const lines = body.replace(/\r\n?/gu, "\n").split("\n");
  const heading = (line: string) => /^(#{1,4})\s/u.exec(line.trim())?.[1]?.length;
  const bold = (line: string) => /^\*\*[^*]+\*\*:?\s*$/u.test(line.trim());
  const start = lines.findIndex(line => decisionsHeading.test(line.trim()));
  if (start <= 0) return body;
  const level = heading(lines[start]!) ?? 4;
  let end = start + 1;
  while (end < lines.length && !((heading(lines[end]!) ?? 99) <= level) && !bold(lines[end]!)) end++;
  return [...lines.slice(start, end), "", ...lines.slice(0, start), ...lines.slice(end)].join("\n").trim();
}
