import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import { planNative } from "../native-plan.js";
import type { Candidate } from "../native-select.js";
import { entry } from "./fixtures.js";

const dirs: string[] = [];
afterAll(() => { for (const d of dirs) rmSync(d, { recursive: true, force: true }); });
function repo(files: Record<string, string> = {}): string {
  const root = mkdtempSync(join(tmpdir(), "mex-plan-"));
  dirs.push(root);
  for (const [path, text] of Object.entries(files)) { mkdirSync(join(root, path, ".."), { recursive: true }); writeFileSync(join(root, path), text); }
  return root;
}
const team = (id: string, scope = "**"): Candidate => ({ level: "team", entry: entry(id, { scope: [scope] }, `Rule ${id}.`) });
const mine = (id: string, scope = "**"): Candidate => ({ level: "personal", entry: entry(id, { scope: [scope] }, `Note ${id}.`) });
const summary = (plan: ReturnType<typeof planNative>) => plan.files.map(f => [f.path, f.sharing, f.agents.join("+"), f.ids.join(",")]);

describe("the who-loads-what plan", () => {
  it("keeps colliding area slugs and personal/team names in distinct files", () => {
    const plan = planNative(repo(), ["claude-code"], [
      team("mx_dash01", "apps/a-b/**"), team("mx_nested", "apps/a/b/**"),
      team("mx_local1", "local/**"), mine("mx_note01"),
    ]);
    expect(new Set(plan.files.map(file => file.path)).size).toBe(4);
    expect(plan.files.find(file => file.sharing === "local")?.ids).toEqual(["mx_note01"]);
  });
  it("Codex gets one AGENTS.md per area; Claude reads it only with no CLAUDE.md at the root or on the way", () => {
    const bare = repo();
    expect(summary(planNative(bare, ["claude-code", "codex"], [team("mx_root01"), team("mx_api001", "apps/api/**")]))).toEqual([
      ["AGENTS.md", "shared", "claude-code+codex", "mx_root01"],
      ["apps/api/AGENTS.md", "shared", "claude-code+codex", "mx_api001"],
    ]);
    // A root CLAUDE.md: Claude Code reads no AGENTS.md at all, so it gets its own rule files.
    const root = repo({ "CLAUDE.md": "# Mine\n" });
    const plan = planNative(root, ["claude-code", "codex"], [team("mx_root01"), team("mx_api001", "apps/api/**")]);
    expect(summary(plan)).toEqual([
      ["AGENTS.md", "shared", "codex", "mx_root01"],
      [".claude/rules/mex.md", "shared", "claude-code", "mx_root01"],
      ["apps/api/AGENTS.md", "shared", "codex", "mx_api001"],
      [expect.stringMatching(/^\.claude\/rules\/mex-area-apps-api-[0-9a-f]{12}\.md$/u), "shared", "claude-code", "mx_api001"],
    ]);
    // A CLAUDE.md on the way down counts the same.
    const nested = repo({ "apps/CLAUDE.md": "# Apps\n" });
    expect(summary(planNative(nested, ["claude-code", "codex"], [team("mx_api001", "apps/api/**")]))[1]?.[2]).toBe("claude-code");
  });

  it("only for agents in use, and never into a file a person wrote", () => {
    const root = repo({ "AGENTS.md": "# Our own rules\n" });
    expect(summary(planNative(root, ["claude-code"], [team("mx_root01")]))).toEqual([[".claude/rules/mex.md", "shared", "claude-code", "mx_root01"]]);
    const plan = planNative(root, ["codex"], [team("mx_root01")]);
    expect(plan.files).toEqual([]);
    expect(plan.notes[0]).toContain("AGENTS.md is yours");
  });

  it("rewrites its own generated files", () => {
    const root = repo({ "AGENTS.md": "<!-- mex:generated by MEX from its entries; edit the entries, not this file -->\n# MEX rules\n" });
    expect(summary(planNative(root, ["codex"], [team("mx_root01")]))).toEqual([["AGENTS.md", "shared", "codex", "mx_root01"]]);
  });

  it("personal notes go in local files; a shared file wins its path", () => {
    const root = repo({ "CLAUDE.md": "# Mine\n" });
    const plan = planNative(root, ["claude-code", "codex"], [team("mx_root01"), mine("mx_note01")]);
    expect(summary(plan)).toEqual([
      ["AGENTS.md", "shared", "codex", "mx_root01"],
      [".claude/rules/mex.md", "shared", "claude-code", "mx_root01"],
      [".claude/rules/mex-local.md", "local", "claude-code", "mx_note01"],
    ]);
    expect(plan.notes[0]).toContain("reach Codex at session start");
  });

  it("never plans CLAUDE.md or CLAUDE.local.md", () => {
    const root = repo();
    const paths = planNative(root, ["claude-code", "codex"], [team("mx_root01"), mine("mx_note01", "apps/web/**")]).files.map(f => f.path);
    expect(paths.some(p => /CLAUDE(\.local)?\.md$/u.test(p))).toBe(false);
  });
});

describe("Copilot's path-scoped instructions", () => {
  it("writes applyTo files only where no generated AGENTS.md already reaches Copilot", () => {
    const plan = planNative(repo(), ["copilot"], [team("mx_root01"), team("mx_api001", "apps/api/**"), mine("mx_note01")]);
    expect(plan.files.map(f => [f.path.replace(/-[0-9a-f]{12}\./u, "."), f.sharing, f.agents.join("+")])).toEqual([
      [".github/instructions/mex.instructions.md", "shared", "copilot"],
      [".github/instructions/mex-area-apps-api.instructions.md", "shared", "copilot"],
      [".github/instructions/mex-local.instructions.md", "local", "copilot"],
    ]);
    expect(plan.files[1]!.text.startsWith('---\napplyTo: "apps/api/**"\n---\n<!-- mex:generated')).toBe(true);
    expect(plan.files[0]!.text.startsWith('---\napplyTo: "**"\n---\n')).toBe(true);
  });

  it("never writes both: Copilot reads the generated AGENTS.md", () => {
    const plan = planNative(repo(), ["codex", "copilot"], [team("mx_api001", "apps/api/**")]);
    expect(summary(plan)).toEqual([["apps/api/AGENTS.md", "shared", "codex+copilot", "mx_api001"]]);
  });

  it("leaves a person's instructions file alone", () => {
    const root = repo({ ".github/instructions/mex.instructions.md": "---\napplyTo: \"**\"\n---\nmine\n" });
    const plan = planNative(root, ["copilot"], [team("mx_root01")]);
    expect(plan.files).toEqual([]);
    expect(plan.notes[0]).toContain("is yours");
  });
});
