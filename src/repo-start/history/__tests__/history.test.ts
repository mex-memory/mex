import { afterAll, describe, expect, it } from "vitest";
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { openRecord } from "../../../record/index.js";
import { realPath } from "../../../record/project.js";
import { buildIndex } from "../../../file-index/build.js";
import { buildCodeFacts } from "../job.js";
import {
  attributeGenerated, changeTogether, hasGeneratedMarker, heldOutPrecision, historyGenerated, importTarget,
  layerRules, PARAM_GRID, parseLog, precisionOn, testSplit, unitOf, validationSplit, wilsonLower, type Commit,
} from "../mine.js";

const temps: string[] = [];
afterAll(() => { for (const path of temps.splice(0)) rmSync(path, { recursive: true, force: true }); });
const c = (hash: number, ...files: string[]): Commit => ({ hash: hash.toString(16).padStart(40, "0"), files });

describe("mining history", () => {
  it("parses git log output and skips merges and blank records", () => {
    const text = `\x1e${"a".repeat(40)}\n\nsrc/a.ts\nsrc/b.ts\n\x1e${"b".repeat(40)}\n\nREADME.md\n\x1enot-a-hash\nx\n`;
    expect(parseLog(text)).toEqual([{ hash: "a".repeat(40), files: ["src/a.ts", "src/b.ts"] }, { hash: "b".repeat(40), files: ["README.md"] }]);
  });

  it("keeps directional pairs at 95% and at least 4 commits, ignoring bulk commits", () => {
    const bulk = c(99, ...Array.from({ length: 31 }, (_, i) => `f${i}`), "schema.ts", "types.ts");
    const commits = [
      c(1, "schema.ts", "types.ts"), c(2, "schema.ts", "types.ts"), c(3, "schema.ts", "types.ts", "x.ts"), c(8, "schema.ts", "types.ts"),
      c(4, "types.ts"), c(5, "types.ts", "y.ts"), c(6, "a.ts", "b.ts"), c(7, "a.ts", "b.ts"), bulk,
    ];
    expect(changeTogether(commits)).toEqual([{ a: "schema.ts", b: "types.ts", confidence: 1, support: 4 }]);
    expect(changeTogether(commits, path => path !== "types.ts")).toEqual([]);
  });

  it("measures held-out precision over firings, learning only from older commits", () => {
    // Newest first: 2 test commits, 8 training commits.
    const commits = [
      c(10, "a.ts", "b.ts"), c(9, "a.ts", "c.ts"),
      ...Array.from({ length: 8 }, (_, i) => c(i + 1, "a.ts", "b.ts")),
    ];
    expect(heldOutPrecision(commits)).toMatchObject({ learn: 8, test: 2, rules: 2, firings: 3, hits: 2, precision: 0.667 });
  });

  it("keeps the test set out of validation and discounts precision with few firings", () => {
    const commits = Array.from({ length: 100 }, (_, i) => c(100 - i, `f${i}`));
    const { test, older } = testSplit(commits);
    const { learn, validation } = validationSplit(commits);
    expect([test.length, validation.length, learn.length]).toEqual([20, 20, 60]);
    expect(validation[0]).toBe(older[0]);
    expect(new Set([...learn, ...validation].filter(commit => test.includes(commit)))).toEqual(new Set());
    expect(wilsonLower(3, 3)).toBeLessThan(wilsonLower(90, 100));
    expect(wilsonLower(0, 0)).toBe(0);
    expect(PARAM_GRID).toHaveLength(120);
    // A learning cap never changes which test commits are counted.
    const bulky = [c(1, ...Array.from({ length: 25 }, (_, i) => `g${i}`)), c(2, "a", "b"), c(3, "a", "b"), c(4, "a", "b")];
    expect(precisionOn(bulky.slice(1), bulky.slice(0, 1), { confidence: 0.9, support: 3, bulkFiles: 5 }).test).toBe(1);
  });

  it("finds generated files by marker, .gitattributes and history", () => {
    expect(hasGeneratedMarker("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n")).toBe(true);
    expect(hasGeneratedMarker("/**\n * @generated\n */")).toBe(true);
    expect(hasGeneratedMarker("a\nb\nc\nd\ne\n// DO NOT EDIT")).toBe(false);
    expect(attributeGenerated("*.pb.go linguist-generated\n/docs/** linguist-generated=true\ndocs/keep.md -linguist-generated\n", ["a/x.pb.go", "docs/a.md", "docs/keep.md", "src/a.go"]))
      .toEqual(["a/x.pb.go", "docs/a.md"]);
    const commits = [c(1, "api.proto", "gen/api.ts"), c(2, "api.proto", "gen/api.ts", "src/use.ts"), c(3, "src/use.ts"), c(4, "api.proto", "gen/once.ts")];
    expect(historyGenerated(commits)).toEqual(["gen/api.ts"]);
  });

  it("derives one-way layer rules at the package or top-level grain", () => {
    const edges = new Map([["app", new Map([["core", 5], ["ui", 1]])], ["ui", new Map([["core", 3], ["app", 2]])]]);
    expect(layerRules(edges)).toEqual([{ from: "core", to: "app", imports: 5 }, { from: "core", to: "ui", imports: 3 }]);
    const packages = [{ path: "packages/core", name: "@x/core" }, { path: "packages/app", name: "@x/app" }];
    expect(unitOf("packages/core/src/a.ts", packages.map(p => p.path))).toBe("packages/core");
    expect(unitOf("scripts/a.ts", packages.map(p => p.path))).toBe("scripts");
    expect(importTarget("packages/app/src/a.ts", "@x/core/sub", packages)).toBe("packages/core");
    expect(importTarget("packages/app/src/a.ts", "../../core/src/b", packages)).toBe("packages/core");
    expect(importTarget("packages/app/src/a.ts", "react", packages)).toBeUndefined();
    expect(importTarget("a.ts", "../../outside", packages)).toBeUndefined();
  });
});

function git(cwd: string, ...args: string[]): string {
  return execFileSync("git", ["-c", "user.email=t@example.com", "-c", "user.name=t", "-c", "commit.gpgsign=false", ...args], { cwd, encoding: "utf8" }).trim();
}
function commit(root: string, files: Record<string, string>, message: string): void {
  for (const [path, text] of Object.entries(files)) { mkdirSync(dirname(join(root, path)), { recursive: true }); writeFileSync(join(root, path), text); }
  git(root, "add", "-A"); git(root, "commit", "-qm", message);
}

describe("the code-facts job on a real repository", () => {
  it("finds the known pairs, layer rule and generated files, and skips a shallow clone", { timeout: 60_000 }, async () => {
    const base = realPath(mkdtempSync(join(tmpdir(), "mex-code-facts-"))); temps.push(base);
    const root = join(base, "repo"); mkdirSync(root); git(root, "init", "-q");
    commit(root, {
      "core/model.ts": "export const model = 1;\n",
      "app/main.ts": "import { model } from \"../core/model\";\nimport { a } from \"../core/a\";\nimport { b } from \"../core/b\";\nexport const main = model;\n",
      "core/a.ts": "export const a = 1;\n", "core/b.ts": "export const b = 1;\n",
      "api.proto": "syntax = \"proto3\";\n", "gen/api.ts": "export {};\n",
      "src/marked.ts": "// Code generated by tool. DO NOT EDIT.\nexport {};\n",
      ".gitattributes": "*.snap linguist-generated\n", "ui/a.snap": "x\n",
    }, "init");
    for (let i = 0; i < 4; i++) commit(root, { "core/model.ts": `export const model = ${i + 2};\n`, "app/main.ts": `${readFileSync(join(root, "app/main.ts"), "utf8")}// ${i}\n` }, `pair ${i}`);
    for (let i = 0; i < 2; i++) commit(root, { "api.proto": `syntax = "proto3"; // ${i}\n`, "gen/api.ts": `export {}; // ${i}\n` }, `gen ${i}`);
    commit(root, { "app/main.ts": `${readFileSync(join(root, "app/main.ts"), "utf8")}// alone\n` }, "app alone");

    const writer = openRecord({ home: join(base, "home"), projectPath: root, isNetwork: () => false });
    const projectId = writer.checkout(root)!.project_id, location = writer.location;
    writer.close();
    await buildIndex({ root, projectId, recordDirectory: location.directory, workers: 0 });
    const facts = await buildCodeFacts(root, projectId, location);
    expect(facts).toMatchObject({ version: 1, skipped: null, commits_read: 8, head: git(root, "rev-parse", "HEAD") });
    expect(facts.change_together).toContainEqual({ a: "core/model.ts", b: "app/main.ts", confidence: 1, support: 5 });
    expect(facts.change_together.find(pair => pair.a === "app/main.ts" && pair.b === "core/model.ts")).toBeUndefined();
    expect(facts.layer_rules).toEqual([{ from: "core", to: "app", imports: 3 }]);
    expect(facts.generated).toEqual([
      { path: "gen/api.ts", signal: "history" },
      { path: "src/marked.ts", signal: "marker" },
      { path: "ui/a.snap", signal: "gitattributes" },
    ]);

    const shallow = join(base, "shallow");
    git(base, "clone", "-q", "--depth", "1", `file://${root}`, shallow);
    expect(await buildCodeFacts(shallow, projectId, location)).toMatchObject({ skipped: "shallow clone", commits_read: 0, change_together: [] });
  });
});
