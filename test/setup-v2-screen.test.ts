/** Every file in a tree but .git, as path → text. */
function tree(root: string): Record<string, string> {
  const out: Record<string, string> = {};
  const walk = (dir: string) => {
    for (const name of readdirSync(dir)) {
      if (name === ".git") continue;
      const path = join(dir, name);
      if (statSync(path).isDirectory()) walk(path);
      else out[relative(root, path).replace(/\\/gu, "/")] = readFileSync(path, "utf8");
    }
  };
  walk(root);
  return out;
}

const PLANTED: Record<string, string[]> = { small: [], conflict: ["rule-conflict"], commands: ["test-command"], monorepo: ["layer-exception"], generated: ["hand-edited"] };
describe("plain and rich write the same things", () => {
  for (const name of ["small", "conflict", "commands", "monorepo", "generated"]) {
    it(name, async () => {
      const source = FIXTURES[name]!();
      const copies = ["plain", "rich"].map(mode => { const target = `${source}-${mode}`; cpSync(source, target, { recursive: true }); return target; });
      const runs = [];
      for (const [i, root] of copies.entries()) runs.push({ root, ...await setup(root, { answer: enter, forceRich: i === 1 }) });
      const [plain, rich] = runs as [typeof runs[0], typeof runs[0]];
      expect(rich.text).not.toBe(plain.text);
      // Each fixture plants one gap, and both screens ask about it.
      expect(plain.answers.map(answer => answer.type)).toEqual(PLANTED[name]);
      expect(rich.answers).toEqual(plain.answers);
      // The same entries, byte for byte.
      expect(rich.notes).toEqual(plain.notes);
      expect(tree(rich.root)).toEqual(tree(plain.root));
    }, 120_000);
  }
});
