const git = (cwd: string, ...args: string[]) => execFileSync("git", ["-C", cwd, "-c", "user.email=t@example.com", "-c", "user.name=t", "-c", "commit.gpgsign=false", ...args], { encoding: "utf8" }).trim();
function put(root: string, files: Record<string, string>) {
  for (const [path, text] of Object.entries(files)) { mkdirSync(dirname(join(root, path)), { recursive: true }); writeFileSync(join(root, path), text); }
}
let made = 0;
function repo(name: string, files: Record<string, string>, extra?: (root: string) => void): string {
  const root = join(base, "fixtures", `${name}-${made++}`);
  mkdirSync(root, { recursive: true });
  git(root, "init", "-q"); put(root, files); git(root, "add", "."); git(root, "commit", "-qm", "init");
  extra?.(root);
  return root;
}
