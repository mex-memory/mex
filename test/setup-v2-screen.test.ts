let home = 0;
async function setup(root: string, options: Partial<Parameters<typeof runRepoStart>[0]> = {}, env: Record<string, string> = {}) {
  const mexHome = join(base, "homes", String(home++));
  vi.stubEnv("MEX_HOME", mexHome);
  const previous = Object.fromEntries(Object.keys(env).map(key => [key, process.env[key]]));
  for (const [key, value] of Object.entries(env)) process.env[key] = value;
  const lines: string[] = [];
  try {
    const result = await runRepoStart({ cwd: root, write: line => lines.push(line), caller: "person", install: false, ...options });
    const reader = openRecordReadOnly();
    const steps = reader && result.projectId ? readSetupSteps(reader, result.projectId) : [];
    reader?.close();
    const location = recordLocation();
    const answers = result.projectId ? Object.values(readAnswers(location, result.projectId).answers).map(({ at: _at, ...answer }) => answer) : [];
    const notes = result.projectId ? [...readNotes(location.home, result.projectId).files].sort() : [];
    return { result, lines, text: lines.join("\n").replace(/\x1b\[[0-9;]*m/gu, ""), steps, answers, notes };
  } finally {
    for (const [key, value] of Object.entries(previous)) if (value === undefined) delete process.env[key]; else process.env[key] = value;
  }
}
