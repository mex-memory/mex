import { render, screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { BrowserRouter } from "react-router-dom";
import { describe, expect, it } from "vitest";
import { MachineHub } from "./MachineHub";

const storefront = "/repos/storefront/knowledge";
const designKit = "/repos/design-kit/knowledge";

function renderFixture(path: string) {
  window.history.replaceState(null, "", path);
  render(<BrowserRouter><MachineHub /></BrowserRouter>);
  return userEvent.setup();
}

async function openBrief(user: ReturnType<typeof userEvent.setup>) {
  const trigger = await screen.findByRole("button", { name: "Preview brief" });
  trigger.focus();
  await user.keyboard("{Enter}");
  const dialog = within(await screen.findByRole("dialog", { name: "Preview brief" }));
  return { trigger, dialog, preview: dialog.getByRole("button", { name: "Preview" }) };
}

describe("Knowledge rules", () => {
  it("opens Rules from Knowledge and shows the files, findings and generated rules", async () => {
    const user = renderFixture(`${storefront}?fixture=home`);
    const entry = await screen.findByRole("link", { name: "Rule files" });
    entry.focus();
    await user.keyboard("{Enter}");
    expect(await screen.findByRole("heading", { level: 1, name: "Rules" })).toHaveFocus();
    expect(window.location.search).toBe("?fixture=home&view=rules");
    const files = screen.getByRole("list", { name: "Rule files" });
    const rows = within(files).getAllByRole("listitem").filter(({ parentElement }) => parentElement === files);
    expect(rows).toHaveLength(4);
    expect(rows[0]).toHaveTextContent("CLAUDE.md");
    expect(rows[0]).toHaveTextContent("Claude Code");
    expect(rows[0]).toHaveTextContent("Whole repo");
    expect(rows[0]).toHaveTextContent("3 entries");
    expect(rows[1]).toHaveTextContent("Codex, Cursor, Copilot, OpenCode");
    expect(within(rows[1]).getByRole("list", { name: "Review findings for AGENTS.md" })).toHaveTextContent("Conflict");
    expect(rows[2]).toHaveTextContent("apps/web");
    expect(within(rows[2]).getByRole("list", { name: "Review findings for .cursor/rules/web.mdc" })).toHaveTextContent("npm run test:legacy");
    const generated = screen.getByRole("region", { name: "Generated by MEX" });
    expect(generated).toHaveTextContent(".claude/rules/mex.md");
    expect(generated).toHaveTextContent(".claude/rules/mex-local.md");

    await user.click(within(screen.getByRole("main")).getByRole("link", { name: "Knowledge" }));
    expect(await screen.findByRole("heading", { level: 1, name: "Knowledge" })).toHaveFocus();
    expect(window.location.search).toBe("?fixture=home");
  });

  it("keeps the saved rows until Refresh and retains the refreshed fixture when reopening Rules", async () => {
    const user = renderFixture(`${storefront}?fixture=rules-stale&view=rules`);
    expect(await screen.findByText("Rule files changed since the last refresh.")).toBeVisible();
    const count = () => screen.getByText("CLAUDE.md", { exact: true }).closest("li");
    expect(count()).toHaveTextContent("2 entries");

    const refresh = screen.getByRole("button", { name: "Refresh" });
    refresh.focus();
    await user.keyboard("{Enter}");
    expect(await screen.findByText("Rule files refreshed.")).toBeVisible();
    expect(refresh).toHaveFocus();
    expect(count()).toHaveTextContent("3 entries");
    expect(screen.queryByText("Rule files changed since the last refresh.")).toBeNull();

    await user.click(within(screen.getByRole("main")).getByRole("link", { name: "Knowledge" }));
    await user.click(screen.getByRole("link", { name: "Rule files" }));
    expect(count()).toHaveTextContent("3 entries");
  });

  it("lets All repos choose a repo and distinguishes empty and unscanned checkouts", async () => {
    const user = renderFixture("/knowledge?fixture=home&view=rules");
    await user.click(await screen.findByRole("link", { name: "Design kit" }));
    expect(window.location.pathname).toBe(designKit);
    expect(screen.getByText("No rule files found.")).toBeVisible();
    const repo = screen.getByRole("combobox", { name: "Repo switcher" });
    await user.selectOptions(repo, "storefront");
    expect(window.location.pathname).toBe(storefront);
    expect(window.location.search).toBe("?fixture=home&view=rules");
    const checkout = screen.getByRole("combobox", { name: "Checkout" });
    checkout.focus();
    await user.selectOptions(checkout, "/work/storefront-checkout");
    expect(checkout).toHaveFocus();
    expect(screen.getByText("Rule files haven’t been scanned.")).toBeVisible();
    expect(screen.queryByText("No rule files found.")).toBeNull();
  });
});

describe("Knowledge brief", () => {
  it("waits for Preview, shows the whole-repo brief and returns focus on Escape", async () => {
    const user = renderFixture(`${storefront}?fixture=home`);
    const { dialog, trigger, preview } = await openBrief(user);
    await waitFor(() => expect(dialog.getByRole("combobox", { name: "Agent" })).toHaveFocus());
    expect(dialog.getByRole("combobox", { name: "Agent" })).toHaveValue("claude-code");
    expect(dialog.queryByRole("heading", { name: "What the agent gets" })).toBeNull();
    await user.tab();
    expect(dialog.getByRole("textbox", { name: "Path (optional)" })).toHaveFocus();
    await user.tab();
    expect(preview).toHaveFocus();
    await user.keyboard("{Enter}");

    expect(await dialog.findByRole("heading", { name: "What the agent gets" })).toHaveFocus();
    expect(dialog.getByText("115 / 550")).toBeVisible();
    expect(dialog.getByText(/\[mex start-preview\]/u)).toHaveTextContent("(mx_checkout)");
    const items = within(dialog.getByRole("list", { name: "Included items (3)" }));
    expect(items.getAllByRole("listitem")).toHaveLength(3);
    expect(items.getByText("mx_checkout").closest("li")).toHaveTextContent("Only you · Up to date · mx_checkout");
    expect(items.getByText("mx_checkout").closest("li")).toHaveTextContent("22 tokens");
    expect(items.getByText("Changelog: Add a changelog entry for visible checkout changes.")).toBeVisible();
    await user.click(dialog.getByText("Rule file coverage (6)"));
    expect(dialog.getByRole("list", { name: "Rule files" })).toHaveTextContent("AGENTS.md");

    await user.keyboard("{Escape}");
    await waitFor(() => expect(trigger).toHaveFocus());
    expect(screen.queryByRole("dialog", { name: "Preview brief" })).toBeNull();
  });

  it("requires a repo in All repos and previews Codex for apps/web", async () => {
    const user = renderFixture("/knowledge?fixture=home");
    const { dialog, preview } = await openBrief(user);
    expect(preview).toHaveAttribute("aria-disabled", "true");
    expect(preview).toHaveAccessibleDescription("Choose a repo to preview a brief.");
    await user.selectOptions(dialog.getByRole("combobox", { name: "Repo" }), "storefront");
    const agent = dialog.getByRole("combobox", { name: "Agent" });
    await user.selectOptions(agent, "codex");
    const path = dialog.getByRole("textbox", { name: "Path (optional)" });
    await user.type(path, "apps/web");
    await user.click(preview);
    expect(await dialog.findByText("91 / 550")).toBeVisible();
    expect(dialog.getByRole("list", { name: "Included items (2)" })).toHaveTextContent("Reproduce a checkout failure with the payment sandbox");
    expect(dialog.queryByText("Keep cart and payment changes in separate transactions", { exact: true })).toBeNull();
    await user.clear(path);
    expect(dialog.queryByRole("heading", { name: "What the agent gets" })).toBeNull();
  });

  it("shows the native header when the brief has no entries", async () => {
    const user = renderFixture(`${designKit}?fixture=home`);
    const { dialog, preview } = await openBrief(user);
    await user.click(preview);
    expect(await dialog.findByText("No entries in this brief.")).toBeVisible();
    expect(dialog.getByText("48 / 550")).toBeVisible();
    expect(dialog.getByText(/\[mex start-preview\]/u)).toBeVisible();
  });

  it("shows the native evaluator error and leaves Preview available to retry", async () => {
    const user = renderFixture(`${storefront}?fixture=brief-failed`);
    const { dialog, preview } = await openBrief(user);
    await user.click(preview);
    expect(await dialog.findByRole("alert")).toHaveTextContent("A brief needs MEX's native check evaluator; reinstall MEX or set MEX_HOOK_BINARY.");
    expect(preview).toHaveFocus();
    expect(preview).not.toHaveAttribute("aria-disabled", "true");
    expect(dialog.queryByRole("heading", { name: "What the agent gets" })).toBeNull();
  });
});
