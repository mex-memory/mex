import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { act, render, screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import type { MachineKnowledgeBrief, MachineKnowledgeRules, MachineProject } from "@mex/hub-contracts/machine";
import { BrowserRouter } from "react-router-dom";
import { afterEach, expect, it, vi } from "vitest";
import { MachineHub } from "./MachineHub";
import { getFixture } from "./fixtures";

const csrf = "test-csrf";
const repoId = "g-" + "a".repeat(24);
const path = "/work/source";
const worktree = "/work/another checkout";
const project: MachineProject = {
  id: repoId, name: "Source", kind: "git", shared: false, provisional: null,
  checkouts: [path, worktree].map(path => ({ path, state: "on", offUntil: null, exists: true })),
};
const knowledge = `/repos/${repoId}/knowledge`;
const home = getFixture("home").overview;
const sample = (name: string, state: "stale" | "current" = "current"): MachineKnowledgeRules => ({
  cache: { state, files: [{ path: name, agents: ["codex"], scope: ["**"], entryCount: 1 }], findings: [] },
  generated: [{ path: ".claude/rules/mex-local.md", sharing: "local" }],
});
const missing: MachineKnowledgeRules = { cache: { state: "missing" }, generated: [] };
const rulesApi = "/api/v1/knowledge/rules";
const previewApi = "/api/v1/knowledge/brief";
const missingEvaluator = "A brief needs MEX's native check evaluator; reinstall MEX or set MEX_HOOK_BINARY.";

function app(route: string, own: (url: string, init: RequestInit | undefined) => Response | undefined, liveEvents = false) {
  let events: Events | undefined;
  class Events extends EventTarget {
    onopen?: () => void;
    constructor() { super(); events = this; }
    close() {}
  }
  const fetch = vi.fn(async (url: string, init?: RequestInit) => {
    const response = own(url, init);
    if (response) return response;
    if (url === "/api/v1/session") return Response.json({
      csrfToken: csrf, expiresAt: "2027-01-02T03:04:05.000Z", version: __MEX_HUB_VERSION__, mode: "background",
    });
    if (url === "/api/v1/projects") return Response.json({ projects: [project] });
    if (url === "/api/v1/jobs") return Response.json([]);
    if (url.startsWith("/api/v1/home?")) return Response.json(home);
    if (url === "/api/v1/review?limit=1") return Response.json({ total: 0, byRepo: {} });
    if (url === "/api/v1/agents") return Response.json({ agents: [] });
    if (url.startsWith("/api/v1/knowledge/landing")) return Response.json({
      generatedAt: "2026-11-25T12:00:00.000Z", groups: { byKind: [], byArea: [] }, needsLook: { total: 0, items: [] },
    });
    throw new Error("Unexpected request " + url);
  });
  vi.stubGlobal("fetch", fetch);
  vi.stubGlobal("EventSource", liveEvents ? Events : undefined);
  if (!window.PointerEvent) vi.stubGlobal("PointerEvent", MouseEvent);
  window.history.replaceState(null, "", route);
  const client = new QueryClient({ defaultOptions: { queries: { gcTime: Infinity } } });
  render(<QueryClientProvider client={client}><BrowserRouter><MachineHub /></BrowserRouter></QueryClientProvider>);
  return { fetch, client, events: () => events };
}

afterEach(() => vi.unstubAllGlobals());

function expectPost(init: RequestInit | undefined, body: unknown) {
  expect(init).toMatchObject({ method: "POST", credentials: "same-origin" });
  expect(JSON.parse(String(init?.body))).toEqual(body);
  const headers = new Headers(init?.headers);
  expect(headers.get("idempotency-key")).toMatch(/^[a-f0-9-]{36}$/u);
  expect(headers.get("x-mex-csrf")).toBe(csrf);
}

it("loads Rule files for the selected checkout and updates it after a protected refresh", async () => {
  const user = userEvent.setup();
  const { fetch } = app(knowledge, (url) => {
    if (url === rulesApi + "/refresh") return Response.json(sample("GEMINI.md"));
    if (!url.startsWith(rulesApi + "?")) return;
    const scope = new URL(url, window.location.origin).searchParams;
    expect(scope.get("repo")).toBe(repoId);
    return Response.json(scope.get("checkout") === path ? sample("AGENTS.md", "stale") : missing);
  });
  await user.click(await screen.findByRole("link", { name: "Rule files" }));
  expect(await screen.findByRole("heading", { level: 1, name: "Rule files" })).toHaveFocus();
  expect(await screen.findByText("Rule files changed since the last refresh.")).toBeVisible();
  expect(screen.getByRole("list", { name: "Rule files" })).toHaveTextContent("AGENTS.md");
  expect(screen.getByRole("region", { name: "Generated by MEX" })).toHaveTextContent("Only you");
  expect(fetch.mock.calls.some(([url]) => url === rulesApi + "/refresh")).toBe(false);

  await user.selectOptions(screen.getByRole("combobox", { name: "Checkout" }), worktree);
  expect(await screen.findByText("Rule files haven’t been scanned.")).toBeVisible();
  expect(screen.queryByText("AGENTS.md")).toBeNull();
  const refresh = screen.getByRole("button", { name: "Refresh" });
  await user.click(refresh);
  expect(await screen.findByText("Rule files refreshed.")).toBeVisible();
  expect(refresh).toHaveFocus();
  expect(screen.getByRole("list", { name: "Rule files" })).toHaveTextContent("GEMINI.md");
  const writes = fetch.mock.calls.filter(([url]) => url === rulesApi + "/refresh");
  expect(writes).toHaveLength(1);
  expectPost(writes[0][1], { repoId, checkout: worktree });
});

it("re-reads the rule snapshot on a Knowledge change event", async () => {
  let response = sample("AGENTS.md");
  const { events, fetch, client } = app(knowledge + "?view=rules", url =>
    url.startsWith(rulesApi + "?") ? Response.json(response) : undefined, true);
  expect(await screen.findByText("AGENTS.md")).toBeVisible();
  await waitFor(() => expect(events()?.onopen).toBeTypeOf("function"));
  await act(() => events()!.onopen!());
  await waitFor(() => expect(client.isFetching({ queryKey: ["knowledge", "rules"] })).toBe(0));
  response = sample("AGENTS.md", "stale");
  await act(() => { events()!.dispatchEvent(new MessageEvent("change", { data: JSON.stringify({ topics: ["knowledge"] }) })); });
  expect(await screen.findByText("Rule files changed since the last refresh.")).toBeVisible();
  expect(fetch.mock.calls.some(([url]) => url === rulesApi + "/refresh")).toBe(false);
});

it("posts the chosen brief scope, displays the evaluator message, and renders a live result", async () => {
  const user = userEvent.setup();
  let unavailable = true;
  const reply = {
    text: "[mex start-preview]\nA live preview.", tokenBound: 57, tokenLimit: 550,
    items: [{ id: "mx_brief", line: "A live preview.", level: "personal", verdict: "held", tokens: 12 }],
    coverage: { files: [{ path: "AGENTS.md", agents: ["codex"], scope: ["apps/web/**"], entryCount: 1 }] },
  } satisfies MachineKnowledgeBrief;
  const { fetch } = app("/knowledge", url => {
    if (url !== previewApi) return;
    return unavailable ? Response.json({
      title: "Brief unavailable", code: "CHECKS_UNAVAILABLE", status: 424, detail: missingEvaluator, requestId: "test",
    }, { status: 424 }) : Response.json(reply);
  });
  await user.click(await screen.findByRole("button", { name: "Preview brief" }));
  const dialog = within(await screen.findByRole("dialog", { name: "Preview brief" }));
  const preview = dialog.getByRole("button", { name: "Preview" });
  expect(preview).toHaveAttribute("aria-disabled", "true");
  expect(fetch.mock.calls.some(([url]) => url === previewApi)).toBe(false);
  await user.selectOptions(dialog.getByRole("combobox", { name: "Repo" }), repoId);
  await user.selectOptions(dialog.getByRole("combobox", { name: "Checkout" }), worktree);
  await user.selectOptions(dialog.getByRole("combobox", { name: "Agent" }), "codex");
  await user.type(dialog.getByRole("textbox", { name: "Path (optional)" }), "apps/web");
  await user.click(preview);
  expect(await dialog.findByRole("alert")).toHaveTextContent(missingEvaluator);
  expect(preview).not.toHaveAttribute("aria-disabled", "true");

  unavailable = false;
  await user.click(preview);
  expect(await dialog.findByRole("heading", { name: "What the agent gets" })).toHaveFocus();
  expect(dialog.getByText("57 / 550")).toBeVisible();
  expect(dialog.getByRole("list", { name: "Included items (1)" })).toHaveTextContent("mx_brief");
  expect(dialog.queryByRole("alert")).toBeNull();
  const writes = fetch.mock.calls.filter(([url]) => url === previewApi);
  expect(writes).toHaveLength(2);
  for (const [, init] of writes) expectPost(init, { repoId, checkout: worktree, agent: "codex", path: "apps/web" });
  expect(new Headers(writes[0][1]?.headers).get("idempotency-key")).not.toBe(new Headers(writes[1][1]?.headers).get("idempotency-key"));
});
